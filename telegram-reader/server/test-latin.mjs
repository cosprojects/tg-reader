// Проверка слоя латиницы и смешанного текста: node server/test-latin.mjs
//
// Ожидания зафиксированы строками: это результат числовой нормализации
// (text-normalize.js) и следом латинской (text-latin.js) — ровно то, что уходит
// в просодию и дальше в Silero. Числовые случаи здесь тоже есть: слой латиницы
// не должен ломать уже работающую нормализацию чисел и годов.
import { normalizeText } from './src/text-normalize.js';
import { normalizeLatin } from './src/text-latin.js';

const prepare = (text) => normalizeLatin(normalizeText(text));

// [вход, ожидание]
const cases = [
  // Тестовый набор из постановки.
  ['В 2026 году AI изменит рынок.', 'В две тысячи двадцать шестом году эй-ай изменит рынок.'],
  ['Мы используем OpenAI API.', 'Мы используем опен эй ай эй-пи-ай.'],
  ['Новый интерфейс сделали в Figma.', 'Новый интерфейс сделали в фигма.'],
  ['React 19 работает вместе с Node.js.', 'реакт девятнадцать работает вместе с ноуд джей эс.'],
  ['UX и UI должны работать вместе.', 'ю-икс и ю-ай должны работать вместе.'],
  ['Подробнее: https://example.com/article', 'Подробнее. Ссылка'],
  ['Напишите на hello@example.com', 'Напишите на электронную почту'],
  ['Наш MVP рассчитан на B2B и B2C.', 'Наш эм-ви-пи рассчитан на би-ту-би и би-ту-си.'],

  // Смешанные слова: латиница, склеенная дефисом с русским словом.
  ['Мы сделали новый AI-сервис на React и Node.js.', 'Мы сделали новый эй-ай сервис на реакт и ноуд джей эс.'],
  ['Telegram-канал про TypeScript и JavaScript', 'телеграм канал про тайпскрипт и джаваскрипт'],
  ['Купите iPhone 15 в Apple Store', 'Купите айфон пятнадцать в эпл стор'],

  // Аббревиатуры: словарь важнее правила «заглавные = аббревиатура».
  ['Наш KPI и CRM в IDE', 'Наш кей-пи-ай и си-ар-эм в ай-ди-и'],
  ['CI/CD и SEO для стартапа', 'си-ай и си-ди и эс-и-о для стартапа'],
  ['SALE и NEW в каталоге', 'сейл и нью в каталоге'],
  ['Мы используем GPT-4o', 'Мы используем джи-пи-ти-четыре-оу'],

  // Незнакомые слова: работает резерв, слово не пропадает и не читается по буквам.
  ['Vite и Webpack в проекте', 'вайт и вебпак в проекте'],
  ['Документация на docs.example.com', 'Документация на ссылку'],
  ['Наш сайт example.ru и канал t.me/reader', 'Наш сайт ссылка и канал ссылка'],

  // Адреса: посимвольное чтение недопустимо, пунктуация предложения сохраняется.
  ['Смотри https://example.com/a, потом t.me/x.', 'Смотри ссылка, потом ссылка.'],
  ['Почта: hello@example.com.', 'Почта. Электронная почта.'],
  ['Пишите по hello@example.com', 'Пишите по электронной почте'],

  // Версии: числовой слой их не трогает, без чтения они остались бы беззвучными.
  ['Смотри v2.5 и 1.2.3', 'Смотри вэ два точка пять и один точка два точка три'],
  ['Мы используем Node.js 22 и Next.js 15', 'Мы используем ноуд джей эс двадцать два и некст джей эс пятнадцать'],

  // Упоминания и хэштеги: латиница в них тоже не должна попадать в синтез.
  ['Напишите в @durov или #news', 'Напишите в упоминание или хэштег'],

  // Числовой слой не ломается: годы, проценты, деньги, даты и телефоны как были.
  ['В 2026 году выросло на 15%', 'В две тысячи двадцать шестом году выросло на пятнадцать процентов'],
  ['1000 ₽ и $20', 'Тысяча рублей и двадцать долларов'],
  ['Он родился 12 мая 2026 года', 'Он родился двенадцатого мая две тысячи двадцать шестого года'],

  // Защищённые конструкции числового слоя остаются как есть: их разбор — не эта задача.
  ['Дата 25.09.2026 в отчёте', 'Дата 25.09.2026 в отчёте'],
  ['ID 1234567 для запроса', 'ай-ди 1234567 для запроса'],
];

let failures = 0;

for (const [input, expected] of cases) {
  const actual = prepare(input);
  if (actual === expected) {
    console.log(`✓ ${input}`);
  } else {
    failures += 1;
    console.error(`✗ ${input}\n    ожидалось: ${expected}\n    получено:  ${actual}`);
  }
}

// Инвариант: после подготовки в тексте для синтеза не должно остаться латинских букв.
// Иначе часть уйдёт в Silero без SSML (без пауз), а слово пропадёт из озвучки.
const latinLeft = cases.map(([input]) => [input, prepare(input)]).filter(([, out]) => /[A-Za-z]/.test(out));
if (latinLeft.length === 0) {
  console.log('✓ латиницы в подготовленном тексте не остаётся');
} else {
  failures += 1;
  console.error(`✗ латиница осталась: ${latinLeft.map(([input]) => input).join('; ')}`);
}

// Инвариант: одиночный латинский токен без русского окружения — тот случай, который
// раньше ронял синтез с ValueError. Проверяем, что он превращается в русские буквы.
for (const token of ['AI', 'API', 'UX', 'UI', 'GPT', 'MVP', 'SaaS', 'B2B', 'B2C', 'URL', 'OpenAI', 'Node.js', 'TypeScript', 'GitHub']) {
  const out = prepare(token);
  if (/[A-Za-z]/.test(out) || out.trim() === '') {
    failures += 1;
    console.error(`✗ одиночный токен ${token} → ${JSON.stringify(out)}`);
  }
}
console.log('✓ одиночные латинские токены превращаются в русские буквы');

console.log(`\nПроверок: ${cases.length + 2 + 14}, ошибок: ${failures}`);
process.exit(failures === 0 ? 0 : 1);
