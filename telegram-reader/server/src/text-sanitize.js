// Очистка текста под набор символов модели Silero.
//
// Зачем. У модели есть свой алфавит:
//   '!+,-.:;?абвгдежзийклмнопрстуфхцчшщъыьэюяё–… ' (плюс служебные '_~|')
// Обычно пакет сам выкидывает всё лишнее (prepare_text_input), но если в тексте есть
// звёздочка «*», он уходит на ветку «focus words» и берёт исходный текст БЕЗ фильтра.
// Тогда первая же скобка или цифра роняет синтез целиком:
//   KeyError: '('   /   KeyError: '1'
// Такой пост нельзя озвучить вообще, поэтому чистим текст сами — до модели, но после
// просодии: она распознаёт заголовки и списки по «#», «*» и цифрам, и до неё эти
// символы удалять нельзя.
//
// Цифры удаляются: модель их не произносит (их и сейчас выкидывает её же фильтр),
// а на ветке «focus» они приводят к падению. Числа, годы и проценты к этому моменту уже
// развёрнуты в слова слоем text-normalize.js — удаляются только те цифры, что остались
// внутри защищённых конструкций (даты, телефоны, длинные идентификаторы).
//
// Знак ударения «+» перед гласной сохраняется: его ставит слой произношения, и он
// входит в алфавит модели. Одиночный «+» (например «2+2») удаляется.

// Символы, которые модель принимает. Пробел и перевод строки обрабатываются отдельно.
const SAFE = /[а-яёА-ЯЁ!,\-.:;?–—…]/i;
// «+» считается знаком ударения, только если стоит прямо перед гласной.
const STRESS = /(?<=[а-яёА-ЯЁ])\+(?=[аеёиоуыэюяАЕЁИОУЫЭЮЯ])/g;
const KEEP = '\u0001';

// Текстовый узел SSML → текст без символов, на которых модель падает.
export function sanitizeSileroText(text) {
  const source = String(text ?? '');
  if (!source) return source;

  const marked = source.replace(STRESS, KEEP);
  let result = '';

  for (const char of marked) {
    if (char === KEEP) result += '+';
    else if (SAFE.test(char)) result += char;
    else if (/\s/.test(char)) result += ' ';
  }

  return result.replace(/[^\S\n]{2,}/g, ' ');
}

// То же для размеченного текста: чистим только текстовые узлы, теги (<speak>, <break/>)
// остаются нетронутыми.
export function sanitizeSileroSsml(ssml) {
  const source = String(ssml ?? '');
  if (!source.includes('<')) return sanitizeSileroText(source);
  return source.replace(/>([^<]*)/g, (_match, node) => `>${sanitizeSileroText(node)}`);
}

// Для отладки и тестов: перечень символов, которые переживают очистку.
export const SILERO_SAFE_CHARS = '!+,-.:;?–—… и русские буквы, пробел';
