// Проверка слоя нормализации текста: node server/test-normalize.mjs
//
// Случаи подобраны по двум группам: что нормализатор обязан превращать в слова
// и что он не имеет права трогать. Ожидания зафиксированы строками, поэтому
// любое изменение поведения сразу видно.
import { normalizeText } from './src/text-normalize.js';

const cases = [
  // Годы: форма зависит от падежа слова «год».
  ['В 2026 году компания выпустила 15% новых продуктов.', 'В две тысячи двадцать шестом году компания выпустила пятнадцать процентов новых продуктов.'],
  ['2026 год', 'Две тысячи двадцать шестой год'],
  ['2024 год', 'Две тысячи двадцать четвёртый год'],
  ['в 2024 году', 'в две тысячи двадцать четвёртом году'],
  ['выборы 2026 года против выборов 2021 года', 'выборы две тысячи двадцать шестого года против выборов две тысячи двадцать первого года'],
  ['с 2020 года', 'с две тысячи двадцатого года'],
  ['до 1991 года', 'до тысяча девятьсот девяносто первого года'],
  ['2000 год', 'Двухтысячный год'],
  ['1900 год', 'Тысяча девятисотый год'],
  ['в 2026 случилось', 'в две тысячи двадцать шестом случилось'],

  // Обычные числа.
  ['10, 25, 100 и 1500', 'Десять, двадцать пять, сто и тысяча пятьсот'],
  ['1500', 'Тысяча пятьсот'],
  ['приехало 2000 человек', 'приехало две тысячи человек'],

  // Дроби.
  ['3.14 и 1.5', 'Три целых четырнадцать сотых и одна целая пять десятых'],

  // Проценты: форма слова зависит от последней цифры.
  ['15%, 1%, 2% и 11%', 'Пятнадцать процентов, один процент, два процента и одиннадцать процентов'],

  // Деньги.
  ['1000 ₽ и $20', 'Тысяча рублей и двадцать долларов'],
  ['20 долларов', 'Двадцать долларов'],

  // Даты: день — порядковое числительное в родительном падеже.
  ['12 мая 2026 года', 'Двенадцатого мая две тысячи двадцать шестого года'],
  ['25 сентября', 'Двадцать пятого сентября'],

  // Не трогаем: ссылки, почта, упоминания, даты, версии, время, идентификаторы.
  ['https://example.com/page?id=42 читай тут', 'https://example.com/page?id=42 читай тут'],
  ['пиши на user@example.com', 'пиши на user@example.com'],
  ['канал @durov и #новости', 'канал @durov и #новости'],
  ['25.09.2026 и 2026-09-25', '25.09.2026 и 2026-09-25'],
  ['версия v2.5 и 1.2.3', 'версия v2.5 и 1.2.3'],
  ['в 12:30', 'в 12:30'],
  ['ООО «Ромашка» и РФ', 'ООО «Ромашка» и РФ'],
  ['заказ 1234567890', 'заказ 1234567890'],

  // Латиница с числом: число произносится словами, буквы не трогаем.
  ['iPhone 16 вышел', 'iPhone шестнадцать вышел'],
];

let failed = 0;
for (const [input, expected] of cases) {
  const actual = normalizeText(input);
  if (actual !== expected) {
    failed += 1;
    console.log(`ОШИБКА\n  ORIGINAL:   ${input}\n  ОЖИДАЛОСЬ:  ${expected}\n  ПОЛУЧИЛОСЬ: ${actual}\n`);
  }
}

console.log(`Проверок: ${cases.length}, ошибок: ${failed}`);
process.exit(failed === 0 ? 0 : 1);
